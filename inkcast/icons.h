// Маппинг OWM icon code -> иконка 48x48 (текущая погода)
inline const unsigned char* getWeatherIcon48(const String& iconCode) {
  if (iconCode == "01d")                          return icon48_clear_day;
  if (iconCode == "01n")                          return icon48_clear_night;
  if (iconCode == "02d" || iconCode == "02n")     return icon48_few_clouds;
  if (iconCode == "03d" || iconCode == "03n")     return icon48_cloudy;
  if (iconCode == "04d" || iconCode == "04n")     return icon48_overcast;
  if (iconCode == "09d" || iconCode == "09n")     return icon48_heavy_rain;
  if (iconCode == "10d" || iconCode == "10n")     return icon48_rain;
  if (iconCode == "11d" || iconCode == "11n")     return icon48_thunderstorm;
  if (iconCode == "13d" || iconCode == "13n")     return icon48_snow;
  if (iconCode == "50d" || iconCode == "50n")     return icon48_mist;
  return icon48_cloudy; // fallback
}

